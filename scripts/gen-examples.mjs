// Regenerates src/lib/examples/manifest.ts from src/lib/examples/datasets/*.json.
// Run after adding or removing an example:  npm run gen:examples
import { readdirSync, writeFileSync } from "node:fs";
const dir = "src/lib/examples/datasets";
const ids = readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort();
const ident = (id) => "ex_" + id.replace(/[^a-zA-Z0-9]/g, "_");
const out = `// AUTO-GENERATED by scripts/gen-examples.mjs — do not edit by hand.
import type { RawExample } from "./types";
${ids.map((id) => `import ${ident(id)} from "./datasets/${id}.json";`).join("\n")}

export const RAW_EXAMPLES: RawExample[] = [
${ids.map((id) => `  ${ident(id)} as RawExample,`).join("\n")}
];
`;
writeFileSync("src/lib/examples/manifest.ts", out);
// Loader-only file for client bundles.
writeFileSync(
  "src/lib/examples/loaders.ts",
  `// AUTO-GENERATED by scripts/gen-examples.mjs — do not edit by hand.\nexport const EXAMPLE_IDS = ${JSON.stringify(ids)};\n\nexport const EXAMPLE_LOADERS: Record<string, () => Promise<{ default: unknown }>> = {\n${ids.map((id) => `  "${id}": () => import("./datasets/${id}.json"),`).join("\n")}\n};\n`,
);
console.log(`Wrote manifest for ${ids.length} examples`);
